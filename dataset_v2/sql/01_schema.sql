-- 2) HUMAN RESOURCES (13)
-- ============================================================
CREATE TABLE hr.positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    department_id BIGINT NOT NULL REFERENCES org.departments(id),
    code VARCHAR(40) NOT NULL,
    name VARCHAR(150) NOT NULL,
    job_level VARCHAR(30),
    employment_type VARCHAR(30) NOT NULL DEFAULT 'FULL_TIME',
    min_salary NUMERIC(18,2),
    max_salary NUMERIC(18,2),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    UNIQUE(tenant_id, code)
);

CREATE TABLE hr.employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    branch_id BIGINT NOT NULL REFERENCES org.branches(id),
    department_id BIGINT NOT NULL REFERENCES org.departments(id),
    team_id BIGINT REFERENCES org.teams(id),
    position_id BIGINT REFERENCES hr.positions(id),
    manager_id BIGINT REFERENCES hr.employees(id),
    employee_code VARCHAR(40) NOT NULL,
    full_name VARCHAR(180) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(40),
    hire_date DATE NOT NULL,
    employment_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    base_salary NUMERIC(18,2) NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(tenant_id, employee_code),
    UNIQUE(email),
    CHECK (employment_status IN ('ACTIVE','ON_LEAVE','INACTIVE','TERMINATED'))
);

ALTER TABLE org.branches ADD CONSTRAINT fk_branch_manager FOREIGN KEY (manager_employee_id) REFERENCES hr.employees(id);
ALTER TABLE org.departments ADD CONSTRAINT fk_department_manager FOREIGN KEY (manager_employee_id) REFERENCES hr.employees(id);
ALTER TABLE org.cost_centers ADD CONSTRAINT fk_cost_center_manager FOREIGN KEY (manager_employee_id) REFERENCES hr.employees(id);

CREATE TABLE hr.employee_job_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES hr.employees(id),
    old_department_id BIGINT REFERENCES org.departments(id),
    new_department_id BIGINT REFERENCES org.departments(id),
    old_position_id BIGINT REFERENCES hr.positions(id),
    new_position_id BIGINT REFERENCES hr.positions(id),
    effective_date DATE NOT NULL,
    change_type VARCHAR(40) NOT NULL,
    reason TEXT,
    approved_by_employee_id BIGINT REFERENCES hr.employees(id)
);

CREATE TABLE hr.employment_contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES hr.employees(id),
    contract_number VARCHAR(60) UNIQUE NOT NULL,
    contract_type VARCHAR(30) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE,
    base_salary NUMERIC(18,2) NOT NULL,
    working_hours_per_week NUMERIC(6,2) DEFAULT 40,
    signed_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
);

CREATE TABLE hr.attendance_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES hr.employees(id),
    work_date DATE NOT NULL,
    check_in_time TIMESTAMPTZ,
    check_out_time TIMESTAMPTZ,
    working_hours NUMERIC(6,2),
    overtime_hours NUMERIC(6,2) DEFAULT 0,
    attendance_status VARCHAR(30) NOT NULL,
    source VARCHAR(30) DEFAULT 'SYSTEM',
    UNIQUE(employee_id, work_date)
);

CREATE TABLE hr.leave_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    annual_entitlement_days NUMERIC(6,2) DEFAULT 0,
    is_paid BOOLEAN NOT NULL DEFAULT TRUE,
    requires_approval BOOLEAN NOT NULL DEFAULT TRUE,
    carry_forward_allowed BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    UNIQUE(tenant_id, code)
);

CREATE TABLE hr.leave_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES hr.employees(id),
    leave_type_id BIGINT NOT NULL REFERENCES hr.leave_types(id),
    fiscal_year INTEGER NOT NULL,
    entitled_days NUMERIC(6,2) NOT NULL DEFAULT 0,
    used_days NUMERIC(6,2) NOT NULL DEFAULT 0,
    remaining_days NUMERIC(6,2) GENERATED ALWAYS AS (entitled_days - used_days) STORED,
    UNIQUE(employee_id, leave_type_id, fiscal_year)
);

CREATE TABLE hr.leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES hr.employees(id),
    leave_type_id BIGINT NOT NULL REFERENCES hr.leave_types(id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    total_days NUMERIC(6,2) NOT NULL,
    reason TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    approved_by_employee_id BIGINT REFERENCES hr.employees(id),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (end_date >= start_date),
    CHECK (status IN ('PENDING','APPROVED','REJECTED','CANCELLED'))
);

CREATE TABLE hr.payroll_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    branch_id BIGINT REFERENCES org.branches(id),
    payroll_period VARCHAR(20) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    payment_date DATE,
    total_gross NUMERIC(18,2) DEFAULT 0,
    total_deductions NUMERIC(18,2) DEFAULT 0,
    total_net NUMERIC(18,2) DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    UNIQUE(tenant_id, branch_id, payroll_period)
);

CREATE TABLE hr.payroll_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payroll_run_id BIGINT NOT NULL REFERENCES hr.payroll_runs(id) ON DELETE CASCADE,
    employee_id BIGINT NOT NULL REFERENCES hr.employees(id),
    base_salary NUMERIC(18,2) DEFAULT 0,
    allowances NUMERIC(18,2) DEFAULT 0,
    overtime_pay NUMERIC(18,2) DEFAULT 0,
    bonus NUMERIC(18,2) DEFAULT 0,
    deductions NUMERIC(18,2) DEFAULT 0,
    tax_amount NUMERIC(18,2) DEFAULT 0,
    net_salary NUMERIC(18,2) DEFAULT 0,
    UNIQUE(payroll_run_id, employee_id)
);

CREATE TABLE hr.performance_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES hr.employees(id),
    reviewer_employee_id BIGINT NOT NULL REFERENCES hr.employees(id),
    review_period VARCHAR(30) NOT NULL,
    performance_score NUMERIC(5,2),
    goal_score NUMERIC(5,2),
    competency_score NUMERIC(5,2),
    comments TEXT,
    review_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'FINAL'
);

CREATE TABLE hr.employee_benefits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES hr.employees(id),
    benefit_type VARCHAR(80) NOT NULL,
    provider VARCHAR(150),
    start_date DATE NOT NULL,
    end_date DATE,
    employee_contribution NUMERIC(18,2) DEFAULT 0,
    employer_contribution NUMERIC(18,2) DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
);

CREATE TABLE hr.training_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES hr.employees(id),
    course_name VARCHAR(180) NOT NULL,
    provider VARCHAR(150),
    start_date DATE,
    completion_date DATE,
    score NUMERIC(5,2),
    certificate_code VARCHAR(80),
    status VARCHAR(30) NOT NULL DEFAULT 'COMPLETED'
);

