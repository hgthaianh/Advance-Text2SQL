-- ============================================================
-- 1) ORGANIZATION (6)
-- ============================================================
CREATE TABLE org.tenants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) UNIQUE NOT NULL,
    name VARCHAR(180) NOT NULL,
    tax_code VARCHAR(50),
    country VARCHAR(80) NOT NULL DEFAULT 'Vietnam',
    currency CHAR(3) NOT NULL DEFAULT 'VND',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE org.locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    code VARCHAR(40) NOT NULL,
    name VARCHAR(150) NOT NULL,
    address_line VARCHAR(255),
    city VARCHAR(100),
    province VARCHAR(100),
    country VARCHAR(80) NOT NULL DEFAULT 'Vietnam',
    latitude NUMERIC(9,6),
    longitude NUMERIC(9,6),
    UNIQUE(tenant_id, code)
);

CREATE TABLE org.branches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    location_id BIGINT REFERENCES org.locations(id),
    code VARCHAR(40) NOT NULL,
    name VARCHAR(150) NOT NULL,
    manager_employee_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(tenant_id, code)
);

CREATE TABLE org.departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    branch_id BIGINT NOT NULL REFERENCES org.branches(id),
    parent_department_id BIGINT REFERENCES org.departments(id),
    code VARCHAR(40) NOT NULL,
    name VARCHAR(150) NOT NULL,
    manager_employee_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(tenant_id, branch_id, code)
);

CREATE TABLE org.teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    branch_id BIGINT NOT NULL REFERENCES org.branches(id),
    department_id BIGINT NOT NULL REFERENCES org.departments(id),
    code VARCHAR(50) NOT NULL,
    name VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(tenant_id, code)
);

CREATE TABLE org.cost_centers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    department_id BIGINT REFERENCES org.departments(id),
    code VARCHAR(40) NOT NULL,
    name VARCHAR(150) NOT NULL,
    manager_employee_id BIGINT,
    annual_budget NUMERIC(18,2) DEFAULT 0,
    currency CHAR(3) NOT NULL DEFAULT 'VND',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    UNIQUE(tenant_id, code)
);

