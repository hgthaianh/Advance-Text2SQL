-- ------------------------------------------------------------
-- Reset identity sequences after explicit IDs.
-- ------------------------------------------------------------
DO $$
DECLARE r RECORD; seq_name text; max_id bigint;
BEGIN
  FOR r IN
    SELECT n.nspname AS schema_name, c.relname AS table_name
    FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE c.relkind='r' AND n.nspname IN ('org','hr','iam','customer','product','inventory','procurement','sales','finance','support','audit')
      AND EXISTS (
        SELECT 1 FROM information_schema.columns ic
        WHERE ic.table_schema=n.nspname AND ic.table_name=c.relname AND ic.column_name='id'
      )
  LOOP
    seq_name := pg_get_serial_sequence(format('%I.%I',r.schema_name,r.table_name),'id');
    IF seq_name IS NOT NULL THEN
      EXECUTE format('SELECT COALESCE(MAX(id),0) FROM %I.%I',r.schema_name,r.table_name) INTO max_id;
      PERFORM setval(seq_name, GREATEST(max_id,1), max_id>0);
    END IF;
  END LOOP;
END $$;

