CREATE TABLE iam.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    branch_id BIGINT REFERENCES org.branches(id),
    department_id BIGINT REFERENCES org.departments(id),
    team_id BIGINT REFERENCES org.teams(id),
    employee_id BIGINT UNIQUE REFERENCES hr.employees(id),
    username VARCHAR(100) UNIQUE NOT NULL,
    full_name VARCHAR(180) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (status IN ('ACTIVE','INACTIVE','LOCKED'))
);

CREATE TABLE iam.roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT REFERENCES org.tenants(id),
    code VARCHAR(60) NOT NULL,
    name VARCHAR(120) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE(tenant_id, code)
);

CREATE TABLE iam.permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(120) UNIQUE NOT NULL,
    resource_type VARCHAR(40) NOT NULL,
    schema_name VARCHAR(63) NOT NULL,
    table_name VARCHAR(63) NOT NULL,
    column_name VARCHAR(63),
    action VARCHAR(30) NOT NULL,
    description TEXT
);

CREATE TABLE iam.user_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES iam.users(id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES iam.roles(id) ON DELETE CASCADE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    valid_to TIMESTAMPTZ,
    UNIQUE(user_id, role_id)
);

CREATE TABLE iam.role_permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES iam.roles(id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES iam.permissions(id) ON DELETE CASCADE,
    UNIQUE(role_id, permission_id)
);

CREATE TABLE iam.user_scopes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES iam.users(id) ON DELETE CASCADE,
    tenant_id BIGINT NOT NULL REFERENCES org.tenants(id),
    branch_id BIGINT REFERENCES org.branches(id),
    department_id BIGINT REFERENCES org.departments(id),
    team_id BIGINT REFERENCES org.teams(id),
    scope_type VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (scope_type IN ('GLOBAL','TENANT','BRANCH','DEPARTMENT','TEAM','OWNER'))
);

CREATE TABLE iam.table_access_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES iam.roles(id) ON DELETE CASCADE,
    schema_name VARCHAR(63) NOT NULL,
    table_name VARCHAR(63) NOT NULL,
    can_select BOOLEAN NOT NULL DEFAULT FALSE,
    row_scope_mode VARCHAR(30) NOT NULL DEFAULT 'INHERIT_USER_SCOPE',
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE(role_id, schema_name, table_name)
);

CREATE TABLE iam.column_access_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES iam.roles(id) ON DELETE CASCADE,
    schema_name VARCHAR(63) NOT NULL,
    table_name VARCHAR(63) NOT NULL,
    column_name VARCHAR(63) NOT NULL,
    can_select BOOLEAN NOT NULL DEFAULT TRUE,
    can_filter BOOLEAN NOT NULL DEFAULT TRUE,
    mask_type VARCHAR(30),
    UNIQUE(role_id, schema_name, table_name, column_name)
);

CREATE TABLE iam.login_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES iam.users(id),
    session_token_hash TEXT NOT NULL,
    ip_address INET,
    user_agent TEXT,
    login_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);

